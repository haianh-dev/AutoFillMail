/* Đọc templates/*.html → sinh app/templates.generated.js (nhúng chuỗi, giữ nguyên từng ký tự). */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const names = ['kmdh', 'nvtch', 'dsnh', 'httt'];

const out = {};
for (const name of names) {
  const path = join(root, 'templates', name + '.html');
  if (!existsSync(path)) {
    console.error('LỖI: thiếu file template: ' + path);
    process.exit(1);
  }
  const content = readFileSync(path, 'utf8');
  out[name] = content;
  const sha = createHash('sha256').update(content).digest('hex').slice(0, 8);
  console.log(`${name}.html: ${Buffer.byteLength(content, 'utf8')} bytes, sha256:${sha}`);
}

const header = '/* AUTO-GENERATED by scripts/build-templates.mjs — DO NOT EDIT */\n';
const body = 'window.SH27_TEMPLATES = ' + JSON.stringify(out) + ';\n';
writeFileSync(join(root, 'app', 'templates.generated.js'), header + body, 'utf8');
console.log('Đã ghi app/templates.generated.js');
